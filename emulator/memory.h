/*
 * Shared Guest Memory — Interface
 *
 * Owns the guest address space used by every component: the fast / debug CPU
 * interpreters, the syscall/peripheral layer and the render loop all read and
 * write this buffer directly.  Kept as a standalone unit so no interpreter is
 * the sole "owner" of memory — peripheral.c / host.c / rsp_stub.c can
 * include this header without depending on any specific CPU implementation.
 *
 * All memory accessors are `static inline` so the compiler can fold them into
 * their callers with zero overhead — identical to the original `static`
 * helpers that lived inside cpu_fast.c.
 */

#ifndef MEMORY_H
#define MEMORY_H

#include "config.h"
#include "emulator_exit.h"

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

/* ── Guest address-space constants ──────────────────────────────────────
 *
 * These are derived from the TCMIPS hardware config (cmake/config.cmake;
 * generated to config.h by configure_file) and MUST stay in sync with the
 * guest-side values in the root CMakeLists.txt.  The guard page is the
 * "no read / no write" sentinel between the heap's upper limit and the stack
 * bottom; a guest that reads or writes into it has overflowed its stack (or
 * heap) and is faulted by the emulator.
 *
 * TCM_MEMORY_SIZE = 64 MB unified RAM. */

/* Guest address space.  Byte-addressable, little-endian, zero-filled on each
 * interpreter run.  Shared, so it is never accessed concurrently without the
 * interpreter's own run/stop coordination. */
extern uint8_t g_emu_memory[TCM_MEMORY_SIZE];

/* ── Initialisation ──────────────────────────────────────────────────── */

/** Reset the guest address space for a new run: zero the whole 64 MB and load
 *  @p size bytes of the guest image at the base.  Call once per run before
 *  starting any interpreter.  Also parses the 4 KB TCM image header for the
 *  .text/.data/.bss base addresses (see memory_get_section_bases). */
void memory_init(const uint8_t *image, uint32_t size);

/* ── Section layout (parsed from the TCM image header) ─────────────── */

/** Base addresses of the guest image's .text/.data/.bss sections, as
 *  declared by the linker in the 4 KB TCM image header.  Takes effect after
 *  the next memory_init().  @return true (and fills the three outputs) when
 *  the header carried the TCM magic and the bases passed the sanity check
 *  (ordered text <= data <= bss, .text no earlier than the 4 KB header zone,
 *  all inside guest RAM); @return false when the layout is unknown or
 *  dubious — the outputs are then left untouched so callers can keep their
 *  own defaults.  Consumed by the RSP stub to answer GDB's 'qOffsets'. */
bool memory_get_image_info(uint32_t *image_size, uint32_t *text_base,
                           uint32_t *data_base, uint32_t *bss_base);

/* ── Memory accessors (static inline, no call overhead) ─────────────── */

/* Access validation: a read/write is illegal when any byte of the access
 * (addr .. addr+width-1) falls outside [0, TCM_MEMORY_SIZE), or when it
 * overlaps the 4 KB guard page (the heap/stack overflow sentinel).  On
 * violation this reports a `!! TCMIPS EMULATOR MEMORY FAULT !!` line to stderr
 * and terminates the emulator with exit code 131 — distinct from 130 (window
 * closed by user) and from a guest's own non-zero exit code.
 *
 * NOTE: this check only guards the interpreted data path (cpu_fast / cpu_debug)
 * and host-side helpers that go through these accessors.  The JIT interpreter
 * performs its data memory accesses through native code generated by SLJIT and
 * does not route through here, so automated tests must use `-mode=fast` (or
 * `-mode=debug`) to exercise this validation — see AUTOTEST.md. */
static inline bool mem_addr_invalid(uint32_t addr, uint32_t width) {
  /* End address inclusive is addr + width - 1; require the whole span to be
   * below TCM_MEMORY_SIZE.  Using uint64_t avoids wrap on addr + width. */
  uint64_t begin = addr;
  uint64_t end = begin + (uint64_t)width - 1u;
  if (end >= TCM_MEMORY_SIZE) {
    return true;
  }
  /* Overlap with the guard page [GADDR, GEND) ? */
  if (begin < (TCM_GUARD_PAGE_ADDR + TCM_GUARD_PAGE_SIZE) &&
      end >= TCM_GUARD_PAGE_ADDR) {
    return true;
  }
  return false;
}

static inline void mem_fault(uint32_t addr, uint32_t width, bool is_write) {
  fprintf(stderr,
          "!! TCMIPS EMULATOR MEMORY FAULT !! %s addr=0x%08x width=%u, "
          "terminating with exit code 131.\n",
          is_write ? "write" : "read", addr, width);
  fflush(stderr);
  exit(TCM_EMULATOR_EXIT_MEMORY_FAULT);
}

static inline uint32_t mem_read_8(uint32_t addr) {
  if (mem_addr_invalid(addr, 1))
    mem_fault(addr, 1, false);
  return g_emu_memory[addr];
}

static inline uint32_t mem_read_16(uint32_t addr) {
  if (mem_addr_invalid(addr, 2))
    mem_fault(addr, 2, false);
  return *(uint16_t *)(g_emu_memory + addr);
}

static inline uint32_t mem_read_32(uint32_t addr) {
  if (mem_addr_invalid(addr, 4))
    mem_fault(addr, 4, false);
  return *(uint32_t *)(g_emu_memory + addr);
}

static inline void mem_write_8(uint32_t addr, uint32_t data) {
  if (mem_addr_invalid(addr, 1))
    mem_fault(addr, 1, true);
  g_emu_memory[addr] = (uint8_t)data;
}

static inline void mem_write_16(uint32_t addr, uint32_t data) {
  if (mem_addr_invalid(addr, 2))
    mem_fault(addr, 2, true);
  *(uint16_t *)(g_emu_memory + addr) = (uint16_t)data;
}

static inline void mem_write_32(uint32_t addr, uint32_t data) {
  if (mem_addr_invalid(addr, 4))
    mem_fault(addr, 4, true);
  *(uint32_t *)(g_emu_memory + addr) = data;
}

#endif /* MEMORY_H */