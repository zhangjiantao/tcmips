/* ---- blit / fill clipping ---- */
static void test_blit_fill(SDL_Surface *screen)
{
    SELF_CHECK("BlitSurface(NULL src) == -1", SDL_BlitSurface(NULL, NULL, screen, NULL) == -1);
    SELF_CHECK("BlitSurface(NULL dst) == -1", SDL_BlitSurface(screen, NULL, NULL, NULL) == -1);

    SDL_Surface *src = SDL_CreateRGBSurface(SDL_SWSURFACE, 16, 16, 32, 0, 0, 0, 0);
    if (!src) { ++g_fail; return; }
    SDL_Rect far = { (Sint16)(screen->w + 50), (Sint16)(screen->h + 50), 16, 16 };
    SELF_CHECK("BlitSurface out-of-bounds rect returns 0 (clipped)",
               SDL_BlitSurface(src, NULL, screen, &far) == 0);
    SELF_CHECK("BlitSurface(same src,dst) == 0",
               SDL_BlitSurface(src, NULL, src, NULL) == 0);
    SDL_FreeSurface(src);

    SELF_CHECK("FillRect negative rect returns 0 (clipped)",
               SDL_FillRect(screen, &(SDL_Rect){ (Sint16)-10, (Sint16)-10, 8, 8 },
                            SDL_MapRGB(screen->format, 255, 0, 0)) == 0);
    /* Fill entire screen and confirm the pixel buffer ends up valid. */
    SELF_CHECK("FillRect NULL rect returns 0 (full screen)",
               SDL_FillRect(screen, NULL, SDL_MapRGB(screen->format, 12, 34, 56)) == 0);
}

