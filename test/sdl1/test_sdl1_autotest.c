/* ---- event queue FIFO ---- */
static void test_events(void)
{
    SDL_Event e1, e2, e3;
    SDL_Event out[4];
    int n;

    memset(&e1, 0, sizeof(e1));
    memset(&e2, 0, sizeof(e2));
    memset(&e3, 0, sizeof(e3));
    memset(out, 0, sizeof(out));

    e1.key.type = SDL_KEYDOWN;
    e1.key.keysym.sym = SDLK_a;
    e2.key.type = SDL_KEYDOWN;
    e2.key.keysym.sym = SDLK_b;

    n = SDL_PeepEvents(&e1, 1, SDL_ADD_EVENT, 0);
    SELF_CHECK("PeepEvents ADD single == 1", n == 1);
    n = SDL_PeepEvents(&e2, 1, SDL_ADD_EVENT, 0);
    SELF_CHECK("PeepEvents ADD second == 1", n == 1);

    n = SDL_PeepEvents(out, 2, SDL_GETEVENT, SDL_KEYDOWNMASK);
    SELF_CHECK("PeepEvents GET count == 2", n == 2);
    SELF_CHECK("PeepEvents FIFO order a,b",
               out[0].key.keysym.sym == SDLK_a && out[1].key.keysym.sym == SDLK_b);

    /* GET with a mask that excludes everything should drain the queue too
     * (unmatched events are dropped) but return 0. */
    e3.key.type = SDL_KEYDOWN;
    e3.key.keysym.sym = SDLK_c;
    n = SDL_PeepEvents(&e3, 1, SDL_ADD_EVENT, 0);
    SELF_CHECK("PeepEvents ADD masked-out == 1", n == 1);
    n = SDL_PeepEvents(out, 1, SDL_GETEVENT, SDL_MOUSEBUTTONDOWNMASK);
    SELF_CHECK("GET(mask miss) returns 0 and drops event", n == 0);
    SELF_CHECK("queue empty after drop",
               SDL_PollEvent(&e3) == 0);

    /* Qeueue-full behaviour: once the queue is full ADD must be refused. */
    SDL_Event many[4];
    memset(many, 0, sizeof(many));
    for (int i = 0; i < 4; ++i)
        many[i].key.type = SDL_KEYDOWN;
    /* Fill any outstanding state to a clean slate, then hammer ADD. */
    while (SDL_PollEvent(&e3)) (void)e3;
    n = 0;
    int total_add = 0;
    /* Drain the queue first by GET with a full mask. */
    SDL_Event drain[64];
    while (SDL_PeepEvents(drain, 1, SDL_GETEVENT, SDL_KEYDOWNMASK) > 0)
        ;
    for (int i = 0; i < 100; ++i) {
        int got = SDL_PeepEvents(many, 1, SDL_ADD_EVENT, 0);
        if (got == 0)
            break;                          /* queue full, refused */
        total_add += got;
    }
    SELF_CHECK("PeepEvents queue offers bounded ADD (drops at cap)",
               total_add > 0 && total_add < 100);
    /* GET should still be able to read what made it in, in order. */
    int nread = 0;
    while (SDL_PeepEvents(drain, 1, SDL_GETEVENT, SDL_KEYDOWNMASK) > 0)
        ++nread;
    SELF_CHECK("PeepEvents GET drains what was enqueued", nread == total_add);

    /* SDL_PushEvent: SDL2-contract extension layered on ADDEVENT. */
    SELF_CHECK("PushEvent NULL rejected", SDL_PushEvent(NULL) == -1);
    SDL_Event pe, got;
    memset(&pe, 0, sizeof(pe));
    memset(&got, 0, sizeof(got));
    pe.key.type = SDL_KEYDOWN;
    pe.key.keysym.sym = SDLK_p;
    SELF_CHECK("PushEvent queues == 1", SDL_PushEvent(&pe) == 1);
    SELF_CHECK("PushEvent event readable via Poll",
               SDL_PollEvent(&got) == 1 && got.key.type == SDL_KEYDOWN &&
                   got.key.keysym.sym == SDLK_p);
}/* ---- cross-format colour correctness ---- */
static void test_crossconvert(SDL_Surface *screen)
{
    /* Fill a 16-bit RGB565 sprite with a known colour, convert it to the
     * screen format (32-bit) and read the centre back.  The loss expansion
     * above RGB555 values must survive the conversion. */
    SDL_Surface *s16 = SDL_CreateRGBSurface(SDL_SWSURFACE, 64, 64, 16, 0, 0, 0, 0);
    if (!s16) { ++g_fail; return; }
    SDL_FillRect(s16, NULL, SDL_MapRGB(s16->format, 255, 128, 0)); /* orange */
    SDL_Surface *cv = SDL_ConvertSurface(s16, screen->format, 0);
    SELF_CHECK("ConvertSurface(16->32) non-NULL", cv != NULL && cv->pixels != NULL);
    if (cv) {
        Uint32 px = *(Uint32 *)((Uint8 *)cv->pixels +
                     cv->pitch * (cv->h / 2) + (cv->w / 2) * 4);
        Uint8 r, g, b, a;
        SDL_GetRGBA(px, cv->format, &r, &g, &b, &a);
        /* 255 in RGB565 red 5-bit -> 248; 128 in green 6-bit stays 128. */
        SELF_CHECK("16->32 colour (R 255->248, G 128, B 0)",
                   r == 248 && g == 128 && b == 0);
        SELF_CHECK("16->32 colour alpha opaque", a == 255);
        SDL_FreeSurface(cv);
    }
    SDL_FreeSurface(s16);

    /* 24-bit RGB888 is lossless; conversion must preserve the colour. */
    SDL_Surface *s24 = SDL_CreateRGBSurface(SDL_SWSURFACE, 64, 64, 24, 0, 0, 0, 0);
    if (!s24) { ++g_fail; return; }
    SDL_FillRect(s24, NULL, SDL_MapRGB(s24->format, 200, 60, 30));
    cv = SDL_ConvertSurface(s24, screen->format, 0);
    SELF_CHECK("ConvertSurface(24->32) non-NULL", cv != NULL && cv->pixels != NULL);
    if (cv) {
        Uint32 px = *(Uint32 *)((Uint8 *)cv->pixels +
                     cv->pitch * (cv->h / 2) + (cv->w / 2) * 4);
        Uint8 r, g, b, a;
        SDL_GetRGBA(px, cv->format, &r, &g, &b, &a);
        SELF_CHECK("24->32 colour preserved (200,60,30)",
                   r == 200 && g == 60 && b == 30);
        SELF_CHECK("24->32 colour alpha opaque", a == 255);
        SDL_FreeSurface(cv);
    }
    SDL_FreeSurface(s24);
}

