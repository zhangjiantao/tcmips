/* Regression for the last remaining SoftStretch deviation: with a NULL
 * dstrect the stretch must cover the FULL DESTINATION surface (upstream
 * 1.2.15 defaults dst_w/dst_h to dst->w/dst->h).  The former implementation
 * defaulted to the source size, so SDL_SoftStretch(img, NULL, screen, NULL)
 * painted only a top-left source-sized corner instead of filling the screen. */
static void test_regress_softstretch_fills_dst(SDL_Surface *screen)
{
    SDL_Surface *src = SDL_CreateRGBSurface(SDL_SWSURFACE, 64, 64, 32, 0, 0, 0, 0);
    if (!src) { ++g_fail; return; }

    /* Four quadrant colours: TL yellow, TR red, BL green, BR blue. */
    SDL_Rect r;
    r.x = 0;              r.y = 0;              r.w = 32; r.h = 32;
    SDL_FillRect(src, &r, SDL_MapRGB(src->format, 255, 255, 0));
    r.x = 32;
    SDL_FillRect(src, &r, SDL_MapRGB(src->format, 255, 0, 0));
    r.x = 0;              r.y = 32;
    SDL_FillRect(src, &r, SDL_MapRGB(src->format, 0, 255, 0));
    r.x = 32;
    SDL_FillRect(src, &r, SDL_MapRGB(src->format, 0, 0, 255));

    SDL_FillRect(screen, NULL, SDL_MapRGB(screen->format, 255, 0, 255));
    SELF_EQ_X32("reg: SoftStretch NULL dstrect rc",
                (unsigned)SDL_SoftStretch(src, NULL, screen, NULL), 0u);

    /* Proportional mapping 64 -> W and 64 -> H: sample one pixel deep into
       each screen quadrant and expect the matching source quadrant colour. */
    int mx = W / 2, my = H / 2;
    Uint32 tl = SDL_MapRGB(screen->format, 255, 255, 0);
    Uint32 tr = SDL_MapRGB(screen->format, 255, 0, 0);
    Uint32 bl = SDL_MapRGB(screen->format, 0, 255, 0);
    Uint32 br = SDL_MapRGB(screen->format, 0, 0, 255);
    SELF_CHECK("reg: NULL dstrect fills the whole destination",
               tcm_reg_px(screen, mx / 2, my / 2) == tl &&
                   tcm_reg_px(screen, W - 10, my / 2) == tr &&
                   tcm_reg_px(screen, mx / 2, H - 10) == bl &&
                   tcm_reg_px(screen, W - 10, H - 10) == br);
    SDL_FreeSurface(src);
}

int main(int argc, char **argv)
{
    (void)argc;
    (void)argv;

    printf("== SDL1 autotest start ==\n");

    if (SDL_Init(SDL_INIT_VIDEO) != 0) {
        printf("[SELF] SDL_Init                         FAIL (%s)\n", SDL_GetError());
        return 1;
    }

    /* SDL1 owns one screen at a time; switch depth per section. */
    SDL_Surface *screen;

    screen = SDL_SetVideoMode(W, H, 32, SDL_SWSURFACE);
    if (!screen) { ++g_fail; printf("[SELF] SetVideoMode(32)               FAIL (%s)\n", SDL_GetError()); SDL_Quit(); return 1; }
    SELF_CHECK("SetVideoMode(32) surface valid", screen->w == W && screen->h == H);
    test_pixfmt32(screen);
    blit_smoke(screen);

    screen = SDL_SetVideoMode(W, H, 16, SDL_SWSURFACE);
    if (!screen) { ++g_fail; printf("[SELF] SetVideoMode(16)               FAIL (%s)\n", SDL_GetError()); SDL_Quit(); return 1; }
    test_pixfmt16(screen);

    screen = SDL_SetVideoMode(W, H, 8, SDL_SWSURFACE | SDL_HWPALETTE);
    if (!screen) { ++g_fail; printf("[SELF] SetVideoMode(8)                FAIL (%s)\n", SDL_GetError()); SDL_Quit(); return 1; }
    test_pixfmt8(screen);
    test_palette_bounds(screen);

    screen = SDL_SetVideoMode(W, H, 32, SDL_SWSURFACE);
    if (!screen) { ++g_fail; printf("[SELF] SetVideoMode(32) re-entry      FAIL (%s)\n", SDL_GetError()); SDL_Quit(); return 1; }

    /* Repeated SDL_Init must be idempotent and NOT clobber the screen. */
    SELF_EQ_X32("SDL_Init (repeat) == 0",
                (unsigned)SDL_Init(SDL_INIT_VIDEO), 0u);
    SELF_CHECK("Screen survives repeated SDL_Init",
               SDL_GetVideoSurface() == screen);

    test_create_bounds();
    test_blit_fill(screen);
    test_convert_ck(screen);
    test_crossconvert(screen);
    test_update(screen);
    test_clip_effect(screen);
    test_softstretch(screen);
    test_clip(screen);
    test_events();
    /* End-to-end framebuffer readback (after Flip) — order matters:
     * each VRAM test repaints and flips the screen itself. */
    test_vram_fill(screen);
    test_vram_fill_rect(screen);
    test_vram_colorkey(screen);
    test_vram_stretch(screen);

    /* Upstream-semantic fixes (see comments above each test). */
    test_fix_srcalpha(screen);
    test_fix_fillrect_writeback(screen);
    test_fix_softstretch_dxoff();
    test_fix_pal8_to_bgra32();

    /* Clip-offset symmetry regressions (formerly standalone targets). */
    test_regress_blit_dst_left(screen);
    test_regress_blit_src_left(screen);
    test_regress_softstretch_src_neg();
    test_regress_softstretch_fills_dst(screen);

    printf("[RESULT] pass=%d fail=%d\n", g_pass, g_fail);
    SDL_Quit();

#ifdef TCM_SDL_DEBUG
    {
        size_t live = tcmips_sdl_debug_alloc_count();
        if (live == 0) {
            ++g_pass;
            printf("[SELF] %-46s PASS\n", "No SDL allocations leaked after Quit");
        } else {
            ++g_fail;
            printf("[SELF] %-46s FAIL (%zu live allocs)\n",
                   "No SDL allocations leaked after Quit", live);
        }
    }
#endif

    if (g_fail == 0) {
        printf("== SDL1 autotest PASS ==\n");
        return 0;
    }
    printf("== SDL1 autotest FAIL ==\n");
    return 1;
}