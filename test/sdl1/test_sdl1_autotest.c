/* * SDL1 self-test: automated boundary / stability checks for libsdl.
 *
 * The TCMIPS emulator forwards the guest's printf output to its own stdout,
 * so this program prints structured `[SELF] ... PASS/FAIL` lines for every
 * assertion and a final `TOTAL` summary whose exit code reports the outcome.
 * Run it like:
 *
 *   TCMIPSEmulator test_sdl1_autotest.tcm -hold=0
 *
 * It does NOT require any interactive input and exits on its own, so it is
 * suitable for automation.
 *
 * Covered areas (all exercised against the real libsdl implementation):
 *   - SDL_MapRGB / SDL_GetRGB across 32/16/8 bpp, incl. RGB565 shift/loss
 *   - pixel-format helpers with NULL format arguments
 *   - SDL_CreateRGBSurface boundary parameters
 *   - SDL_BlitSurface NULL / out-of-range rect clipping
 *   - SDL_FillRect negative / out-of-range rect clipping
 *   - SDL_ConvertSurface NULL input
 *   - SDL_SetColorKey / SDL_SetAlpha NULL surface
 *   - SDL_SoftStretch NULL / non-1:1 scaling (scale + deform)
 *   - SDL_ClipRect set/get semantics
 *   - SDL_PeepEvents ADD / GET FIFO order and mask filtering
 *
 * NOTE: SDL1 owns only one screen; each SetVideoMode() free-allocates the
 * framebuffer, so we switch modes one depth at a time and never hold two
 * screens simultaneously.
 */

#include <SDL/SDL.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

/* For end-to-end framebuffer readback we ask libsdl for the VRAM pointer it
 * already owns (it wraps the pixel-console driver); the guest may read that
 * memory directly.  This couples the test to libsdl's own query interface
 * instead of re-initialising the console underneath it. */
#include <SDL/SDL_tcmips.h>
#include <stdint.h>

/* The leak-query symbol `tcmips_sdl_debug_alloc_count()` is exported by
 * SDL_tcmips.h under `#ifdef TCM_SDL_DEBUG` — and that flag in turn comes
 * from tcm_config.h, generated by the project-level TCM_SDL_DEBUG switch
 * in the root CMakeLists.txt, so this test no longer needs a
 * `-DTCM_SDL_DEBUG` on the command line: it simply hits the `#ifdef` path
 * below whenever the linked libsdl was built with leak tracking. */

/* Only the emulator's pixel console supports a 4:3 screen; request one. */
#define W 640
#define H 480

static int g_pass = 0;
static int g_fail = 0;

#define SELF_CHECK(name, cond)                                                    \
  do {                                                                            \
    if (cond) {                                                                   \
      ++g_pass;                                                                   \
      printf("[SELF] %-46s PASS\n", (name));                                      \
    } else {                                                                      \
      ++g_fail;                                                                   \
      printf("[SELF] %-46s FAIL\n", (name));                                      \
    }                                                                             \
  } while (0)

#define SELF_EQ_X32(name, actual, expected)                                       \
  do {                                                                            \
    unsigned long a = (unsigned long)(actual);                                    \
    unsigned long e = (unsigned long)(expected);                                  \
    if (a == e) {                                                                 \
      ++g_pass;                                                                   \
      printf("[SELF] %-46s PASS\n", (name));                                      \
    } else {                                                                      \
      ++g_fail;                                                                   \
      printf("[SELF] %-46s FAIL (got %lu, want %lu)\n", (name), a, e);            \
    }                                                                             \
  } while (0)

/* ---- 32-bit RGBA (R in low byte) pixel-format round-trip ---- */
static void test_pixfmt32(SDL_Surface *screen)
{
    Uint32 c = SDL_MapRGB(screen->format, 0x12, 0x34, 0x56);
    Uint8 r, g, b, a;
    SDL_GetRGBA(c, screen->format, &r, &g, &b, &a);
    SELF_EQ_X32("32bpp MapRGB low byte = R", c & 0xFFu, 0x12u);
    SELF_CHECK("32bpp RGBA round-trip (R/G/B)",
               r == 0x12 && g == 0x34 && b == 0x56);
    /* Official SDL semantics: MapRGB() maps an RGB triple to an *opaque*
     * pixel, so the alpha channel must read 255 for a 32-bpp RGBA format. */
    SELF_CHECK("32bpp MapRGB alpha = opaque (255)", a == 0xFF);

    /* Explicit MapRGBA must round-trip the whole RGBA channel. */
    Uint32 c4 = SDL_MapRGBA(screen->format, 0x11, 0x22, 0x33, 0xD2);
    Uint8 r2, g2, b2, a2;
    SDL_GetRGBA(c4, screen->format, &r2, &g2, &b2, &a2);
    SELF_CHECK("32bpp MapRGBA/GetRGBA round-trip (RGBA)",
               r2 == 0x11 && g2 == 0x22 && b2 == 0x33 && a2 == 0xD2);

    SELF_EQ_X32("MapRGB(NULL,..) returns 0", SDL_MapRGB(NULL, 1, 2, 3), 0u);
    r = 9; g = 9; b = 9;
    SDL_GetRGB(0, NULL, &r, &g, &b);
    SELF_CHECK("GetRGB(NULL fmt) leaves outputs untouched", r == 9 && g == 9 && b == 9);
}

/* ---- 16-bit RGB565: shift/loss fields ---- */
static void test_pixfmt16(SDL_Surface *screen)
{
    Uint32 c = SDL_MapRGB(screen->format, 255, 255, 255);
    SELF_EQ_X32("16bpp RGB565 full white", c, 0xFFFFu);
    SELF_EQ_X32("16bpp RGB565 Red field", (c & 0xF800u) >> 11, 31u);
    SELF_EQ_X32("16bpp RGB565 Green field", (c & 0x07E0u) >> 5, 63u);
    SELF_EQ_X32("16bpp RGB565 Blue field", c & 0x001Fu, 31u);

    Uint8 r, g, b, a;
    SDL_GetRGBA(c, screen->format, &r, &g, &b, &a);
    /* loss replication: 5-bit 31 -> 248, 6-bit 63 -> 252. */
    SELF_CHECK("16bpp GetRGB red (255->248 via loss)",
               r == 248 && g == 252 && b == 248);
    SELF_CHECK("16bpp GetRGBA alpha = opaque", a == 255);
}

/* ---- 8-bit indexed: palette mapping ---- */
static void test_pixfmt8(SDL_Surface *screen)
{
    SDL_Color pal[4];
    pal[0].r = 0;    pal[0].g = 0;   pal[0].b = 0;
    pal[1].r = 255;  pal[1].g = 0;   pal[1].b = 0;
    pal[2].r = 0;    pal[2].g = 255; pal[2].b = 0;
    pal[3].r = 0;    pal[3].g = 0;   pal[3].b = 255;
    SDL_SetPalette(screen, SDL_LOGPAL, pal, 0, 4);

    Uint32 idx = SDL_MapRGB(screen->format, 255, 0, 0);
    SELF_EQ_X32("8bpp MapRGB -> nearest palette index", idx, 1u);

    Uint8 r, g, b, a;
    SDL_GetRGBA(2, screen->format, &r, &g, &b, &a);
    SELF_CHECK("8bpp GetRGBA -> palette entry (green)",
               r == 0 && g == 255 && b == 0);
    SELF_CHECK("8bpp GetRGBA alpha = opaque", a == 255);
}

