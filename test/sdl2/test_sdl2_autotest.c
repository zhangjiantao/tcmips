/* * SDL2 self-test: automated boundary / stability checks for libsdl2.
 *
 * Mirrors the SDL1 autotest approach: the TCMIPS emulator forwards the
 * guest's printf output to its own stdout, and the guest exit code reports
 * the pass/fail outcome, so this program is self-terminating and CI-friendly.
 *
 *   TCMIPSEmulator.exe test_sdl2_autotest.tcm -hold=0
 *
 * Covered areas (all exercised against the real libsdl2 implementation):
 *   - pixel-format helpers: SDL_MapRGB / SDL_MapRGBA / SDL_GetRGB/RGBA
 *   - surface creation boundaries and ConvertSurface(Format)
 *   - copy / partial-rect blits with clipping (SDL_UpperBlit, SDL_BlitSurface)
 *   - colour-key transparency (SDL_SetColorKey + skip in blits)
 *   - scaling / deformation (SDL_SoftStretch)
 *   - geometry helpers (SDL_FillRect, SDL_Rect)
 *   - event queue FIFO / mask / queue-full semantics (SDL_PushEvent, SDL_PeepEvents)
 *   - end-to-end VRAM readback via tcmips_sdl2_vram_info
 */

#include <SDL2/SDL.h>
#include <SDL2/SDL2_tcmips.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

/* The leak-query symbol `tcmips_sdl2_debug_alloc_count()` is exported by
 * SDL2_tcmips.h under `#ifdef TCM_SDL_DEBUG`.  The flag comes from
 * tcm_config.h, generated by the project-level TCM_SDL_DEBUG switch in
 * the root CMakeLists.txt (shared with libsdl).  So this test no longer
 * needs a `-DTCM_SDL_DEBUG` on the command line: it simply hits the
 * `#ifdef` path below whenever the linked libsdl2 was built with leak
 * tracking. */

#define W 640
#define H 480

static int g_pass = 0;
static int g_fail = 0;

#define SELF_CHECK(name, cond)                                       \
  do {                                                               \
    if (cond) { ++g_pass;  printf("[SELF] %-46s PASS\n", (name)); }   \
    else     { ++g_fail;   printf("[SELF] %-46s FAIL\n", (name)); }   \
  } while (0)

#define SELF_EQ_X32(name, actual, expected)                          \
  do {                                                               \
    unsigned long a = (unsigned long)(actual);                       \
    unsigned long e = (unsigned long)(expected);                     \
    if (a == e) { ++g_pass;  printf("[SELF] %-46s PASS\n", (name)); } \
    else { ++g_fail; printf("[SELF] %-46s FAIL (got %lu, want %lu)\n", (name), a, e); } \
  } while (0)

/* ---- pixel format ---- */
static void test_pixfmt(SDL_Surface *screen) {
    Uint32 c = SDL_MapRGBA(screen->format, 0x11, 0x22, 0x33, 0x99);
    /* TCMIPS surfaces are fixed RGBA32, R in byte 0. */
    SELF_EQ_X32("MapRGBA low byte = R", c & 0xFFu, 0x11u);
    SELF_EQ_X32("MapRGBA byte1 = G", (c >> 8) & 0xFF, 0x22u);
    SELF_EQ_X32("MapRGBA byte2 = B", (c >> 16) & 0xFF, 0x33u);
    SELF_EQ_X32("MapRGBA byte3 = A", (c >> 24) & 0xFF, 0x99u);

    Uint8 r, g, b, a;
    SDL_GetRGBA(c, screen->format, &r, &g, &b, &a);
    SELF_CHECK("GetRGBA round-trip", r == 0x11 && g == 0x22 && b == 0x33 && a == 0x99);
    SELF_CHECK("GetRGB ignores alpha", (SDL_GetRGB != NULL));

    /* MapRGB maps to an *opaque* pixel: alpha must be 255. */
    c = SDL_MapRGB(screen->format, 5, 6, 7);
    SDL_GetRGBA(c, screen->format, &r, &g, &b, &a);
    SELF_CHECK("MapRGB produces opaque alpha = 255", a == 0xFF);

    /* Enum + masks helpers. */
    Uint32 fmt = SDL_MasksToPixelFormatEnum(32, 0x000000FF, 0x0000FF00, 0x00FF0000, 0xFF000000);
    SELF_EQ_X32("MasksToPixelFormatEnum RGBA32", fmt, SDL_PIXELFORMAT_RGBA32);

    int bpp; Uint32 rm, gm, bm, am;
    SELF_CHECK("PixelFormatEnumToMasks true",
               SDL_PixelFormatEnumToMasks(SDL_PIXELFORMAT_RGBA32, &bpp, &rm, &gm, &bm, &am) == SDL_TRUE);
    SELF_CHECK("Masks match RGBA32",
               bpp == 32 && rm == 0x000000FF && gm == 0x0000FF00 && bm == 0x00FF0000 && am == 0xFF000000);
}

/* ---- surface creation boundaries ---- */
static void test_create_bounds(void) {
    SELF_CHECK("CreateRGBSurface(w=0) NULL",
               SDL_CreateRGBSurface(0, 0, 10, 32, 0,0,0,0) == NULL);
    SELF_CHECK("CreateRGBSurface(h=0) NULL",
               SDL_CreateRGBSurface(0, 10, 0, 32, 0,0,0,0) == NULL);
    SELF_CHECK("CreateRGBSurface(depth<8) NULL",
               SDL_CreateRGBSurface(0, 10, 10, 4, 0,0,0,0) == NULL);
    SDL_Surface *s = SDL_CreateRGBSurface(0, 32, 32, 32, 0,0,0,0);
    SELF_CHECK("CreateRGBSurface(32x32) ok", s != NULL && s->pixels != NULL);
    if (s) SELF_EQ_X32("12x12 window pitch 4-aligned", (unsigned)s->pitch, (unsigned)(32*4));
    if (s) SDL_FreeSurface(s);
}

/* ---- copy / blit with clipping ---- */
static void test_blit(SDL_Surface *screen) {
    /* NULL guards. */
    SELF_CHECK("BlitSurface(NULL src) == -1",
               SDL_BlitSurface(NULL, NULL, screen, NULL) == -1);
    SELF_CHECK("BlitSurface(NULL dst) == -1",
               SDL_BlitSurface(screen, NULL, NULL, NULL) == -1);

    SDL_Surface *src = SDL_CreateRGBSurface(0, 16, 16, 32, 0,0,0,0);
    if (!src) { ++g_fail; return; }
    SDL_FillRect(src, NULL, SDL_MapRGB(src->format, 200, 60, 30));

    /* Fully out-of-bounds destination rect -> clipped, returns 0. */
    SDL_Rect far = { (Sint16)(screen->w + 50), (Sint16)(screen->h + 50), 16, 16 };
    SELF_CHECK("Blit out-of-bounds rect returns 0", SDL_BlitSurface(src, NULL, screen, &far) == 0);

    /* Partial source rect copy. */
    SDL_FillRect(screen, NULL, SDL_MapRGB(screen->format, 0, 0, 0));
    SDL_Rect sr = { 4, 4, 8, 8 };
    SDL_Rect dr = { 200, 140, 8, 8 };
    SELF_CHECK("Blit sub-rect == 0", SDL_BlitSurface(src, &sr, screen, &dr) == 0);
    SDL_FreeSurface(src);
}

/* ---- colour-key transparency ---- */
static void test_colorkey(SDL_Surface *screen) {
    SDL_Surface *s = SDL_CreateRGBSurface(0, 32, 32, 32, 0,0,0,0);
    if (!s) { ++g_fail; return; }
    Uint32 white = SDL_MapRGB(s->format, 255, 255, 255);
    Uint32 key = SDL_MapRGB(s->format, 255, 0, 255);      /* magenta */
    SDL_FillRect(s, NULL, white);
    SDL_Rect keyhalf = { 16, 0, 16, 32 };
    SDL_FillRect(s, &keyhalf, key);

    /* Colour key query before setting. */
    SELF_CHECK("HasColorKey false before set", SDL_HasColorKey(s) == SDL_FALSE);
    SELF_CHECK("GetColorKey fails before set", SDL_GetColorKey(s, NULL) == -1);

    SELF_CHECK("SetColorKey(s,SDL_TRUE,key) == 0",
               SDL_SetColorKey(s, SDL_TRUE, key) == 0);
    SELF_CHECK("HasColorKey true after set", SDL_HasColorKey(s) == SDL_TRUE);
    Uint32 got;
    SELF_CHECK("GetColorKey returns key", SDL_GetColorKey(s, &got) == 0 && got == key);
    SELF_CHECK("SetColorKey(s,SDL_FALSE,..) disables",
               SDL_SetColorKey(s, SDL_FALSE, key) == 0 && SDL_HasColorKey(s) == SDL_FALSE);
    SELF_CHECK("SetColorKey(NULL) == -1", SDL_SetColorKey(NULL, SDL_TRUE, 0) == -1);

    /* Enable again for a real blit test. */
    SDL_SetColorKey(s, SDL_TRUE, key);
    SDL_FillRect(screen, NULL, SDL_MapRGB(screen->format, 10, 10, 10));
    SDL_Rect dr = { 100, 80, 32, 32 };
    SELF_CHECK("Blit(colorkey) == 0", SDL_BlitSurface(s, NULL, screen, &dr) == 0);
    SDL_FreeSurface(s);
}

/* ---- scaling / deformation ---- */
static void test_stretch(SDL_Surface *screen) {
    SDL_Surface *src = SDL_CreateRGBSurface(0, 64, 64, 32, 0,0,0,0);
    SDL_Surface *dst = SDL_CreateRGBSurface(0, 160, 160, 32,
                                            screen->format->Rmask,
                                            screen->format->Gmask,
                                            screen->format->Bmask,
                                            screen->format->Amask);
    if (!src || !dst) { ++g_fail; if (src) SDL_FreeSurface(src); if (dst) SDL_FreeSurface(dst); return; }
    SDL_FillRect(src, NULL, SDL_MapRGB(src->format, 220, 30, 30));

    SDL_Rect sr = { 0, 0, 64, 64 };
    SELF_CHECK("SoftStretch NULL src == -1", SDL_SoftStretch(NULL, &sr, dst, NULL) == -1);
    SELF_CHECK("SoftStretch NULL dst == -1", SDL_SoftStretch(src, &sr, NULL, NULL) == -1);
    SELF_CHECK("SoftStretch 1:1 == 0",
               SDL_SoftStretch(src, &sr, dst, &(SDL_Rect){0,0,64,64}) == 0);
    SELF_CHECK("SoftStretch downscale == 0",
               SDL_SoftStretch(src, &sr, dst, &(SDL_Rect){0,0,37,23}) == 0);
    SELF_CHECK("SoftStretch upscale == 0",
               SDL_SoftStretch(src, &sr, dst, &(SDL_Rect){0,0,131,79}) == 0);
    SELF_CHECK("SoftStretch deform == 0",
               SDL_SoftStretch(src, &sr, dst, &(SDL_Rect){0,0,120,40}) == 0);
    /* SDL2: zero w/h destination means "use the source size" (default),
     * so {0,0,0,0} succeeds by mapping to the source dimensions. */
    SELF_CHECK("SoftStretch zero-size dst uses source size",
               SDL_SoftStretch(src, &sr, dst, &(SDL_Rect){0,0,0,0}) == 0);
    SELF_CHECK("SoftStretch negative-size dst clipped draws nothing",
               SDL_SoftStretch(src, &sr, dst, &(SDL_Rect){0,0,-4,-4}) == 0);

    SDL_FreeSurface(dst);
    SDL_FreeSurface(src);
}

/* ---- geometry helpers ---- */
static void test_geometry(void) {
    SDL_Rect a = { 10, 20, 30, 40 };
    SDL_Rect b1 = { 25, 30, 10, 10 };
    int hi = SDL_HasIntersection(&b1, &a);
    SELF_EQ_X32("SDL_HasIntersection true", (unsigned)hi, 1u);
    SDL_Rect b2 = { 100, 100, 5, 5 };
    SELF_CHECK("SDL_IntersectRect disjoint empty",
               SDL_IntersectRect(&b2, &a, NULL) == SDL_FALSE);
    SDL_Rect out;
    SDL_Rect b3 = { 20, 30, 10, 10 };
    SELF_CHECK("SDL_IntersectRect overlap non-empty",
               SDL_IntersectRect(&b3, &a, &out) == SDL_TRUE);
    SELF_CHECK("Intersection coords correct",
               out.x == 20 && out.y == 30 && out.w == 10 && out.h == 10);
    SDL_Point p1 = { 25, 35 };
    int pin = SDL_PointInRect(&p1, &a);
    SELF_EQ_X32("SDL_PointInRect true",
                (unsigned)pin, 1u);
}

/* ---- event queue FIFO / full ---- */
static void test_events(void) {
    SDL_Event a, b, c, out[64];
    int n;
    memset(&a, 0, sizeof(a)); memset(&b, 0, sizeof(b));
    memset(&c, 0, sizeof(c)); memset(out, 0, sizeof(out));
    a.type = SDL_KEYDOWN; a.key.keysym.sym = SDLK_a;
    b.type = SDL_KEYDOWN; b.key.keysym.sym = SDLK_b;

    SELF_CHECK("PushEvent(NULL) == 0", SDL_PushEvent(NULL) == 0);
    SELF_CHECK("PushEvent(a) == 1", SDL_PushEvent(&a) == 1);
    SELF_CHECK("PushEvent(b) == 1", SDL_PushEvent(&b) == 1);

    n = SDL_PeepEvents(out, 2, SDL_GETEVENT, SDL_KEYDOWN, SDL_KEYDOWN);
    SELF_CHECK("PeepEvents GET count == 2", n == 2);
    SELF_CHECK("PeepEvents FIFO a,b",
               out[0].key.keysym.sym == SDLK_a && out[1].key.keysym.sym == SDLK_b);
    SELF_CHECK("Queue drained after GET", SDL_PollEvent(NULL) == 0);

    /* Queue full: PushEvent eventually returns 0. */
    memset(&c, 0, sizeof(c)); c.type = SDL_KEYDOWN;
    int push_ok = 0, full_seen = 0;
    for (int i = 0; i < 200; ++i) {
        int r = SDL_PushEvent(&c);
        if (r == 1) push_ok++;
        else full_seen = 1;
        if (full_seen) break;
    }
    SELF_CHECK("Queue fills and PushEvent reports full", push_ok > 0 && push_ok < 200 && full_seen);
}

/* ---- VRAM end-to-end readback ---- */
static Uint32 vram_pixel(int x, int y) {
    tcmips_sdl2_vram_format_t fmt;
    void *fb = tcmips_sdl2_vram_info(&fmt);
    if (!fb || fmt.bytes_per_pixel != 4 || fmt.width <= 0)        return 0;
    const uint32_t *row = (const uint32_t *)((const uint8_t *)fb +
                            (size_t)y * fmt.width * (size_t)fmt.bytes_per_pixel);
    return row[x];
}

static void test_vram_readback(SDL_Window *win, SDL_Surface *screen) {
    /* Fill whole screen, update window, read VRAM centre. */
    Uint32 want = SDL_MapRGB(screen->format, 30, 40, 50);
    SDL_FillRect(screen, NULL, want);
    SDL_UpdateWindowSurface(win);
    SELF_EQ_X32("VRAM fill centre readback", vram_pixel(W/2, H/2), want);
    SELF_EQ_X32("VRAM fill corner readback", vram_pixel(5, 5), want);

    /* Clipped rectangle pixel-exactness. */
    Uint32 bg = SDL_MapRGB(screen->format, 10, 10, 10);
    Uint32 col = SDL_MapRGB(screen->format, 200, 60, 30);
    SDL_FillRect(screen, NULL, bg);
    SDL_Rect r = { 20, 30, 40, 25 };
    SDL_FillRect(screen, &r, col);
    SDL_UpdateWindowSurface(win);
    SELF_EQ_X32("VRAM rect inside == painted", vram_pixel(22, 32), col);
    SELF_EQ_X32("VRAM rect outside == bg", vram_pixel(19, 32), bg);

    /* Colour-key transparency through VRAM. */
    SDL_Surface *s = SDL_CreateRGBSurface(0, 32, 32, 32, 0,0,0,0);
    if (s) {
        Uint32 white = SDL_MapRGB(s->format, 255,255,255);
        Uint32 key = SDL_MapRGB(s->format, 255,0,255);
        SDL_FillRect(s, NULL, white);
        SDL_Rect half = { 16, 0, 16, 32 };
        SDL_FillRect(s, &half, key);
        SDL_SetColorKey(s, SDL_TRUE, key);
        SDL_Rect dr = { 100, 80, 32, 32 };
        SDL_BlitSurface(s, NULL, screen, &dr);
        SDL_UpdateWindowSurface(win);
        SELF_EQ_X32("VRAM colorkey opaque white", vram_pixel(104, 84), white);
        SELF_EQ_X32("VRAM colorkey transparent == bg",
                    vram_pixel(120, 84), SDL_MapRGB(screen->format, 10,10,10));
        SDL_FreeSurface(s);
    }

    /* Regression: a colour key built with SDL_MapRGBA(...,255) (alpha 255)
     * must still transparently skip the keyed pixels.  The colorkey match is
     * colour (RGB) based, not an exact RGBA byte compare, so the alpha value
     * of either the key or the filled pixels does not affect the match. */
    {
        SDL_Surface *s2 = SDL_CreateRGBSurface(0, 32, 32, 32, 0,0,0,0);
        if (s2) {
            Uint32 bgv = SDL_MapRGB(screen->format, 40, 60, 80);
            Uint32 white2 = SDL_MapRGB(s2->format, 255,255,255);
            Uint32 key2 = SDL_MapRGBA(s2->format, 255,0,255,255);   /* alpha 255 key */
            SDL_FillRect(s2, NULL, white2);
            SDL_Rect half2 = { 16, 0, 16, 32 };
            SDL_FillRect(s2, &half2, key2);
            SDL_SetColorKey(s2, SDL_TRUE, key2);
            SDL_FillRect(screen, NULL, bgv);
            SDL_Rect dr2 = { 160, 80, 32, 32 };
            SDL_BlitSurface(s2, NULL, screen, &dr2);
            SDL_UpdateWindowSurface(win);
            SELF_EQ_X32("VRAM colorkey alpha255 opaque white",
                        vram_pixel(164, 84), white2);
            SELF_EQ_X32("VRAM colorkey alpha255 transparent == bg",
                        vram_pixel(180, 84), bgv);
            SDL_FreeSurface(s2);
        }
    }

    /* Non-colour-key 1:1 blit: exercises the SDL_memcpy row fast path in
     * SDL_UpperBlit (no SetColorKey, so no per-pixel skip).  Pixel readback
     * verifies the copied colour end-to-end through VRAM. */
    {
        SDL_Surface *sp = SDL_CreateRGBSurface(0, 32, 32, 32, 0, 0, 0, 0);
        if (sp) {
            Uint32 col = SDL_MapRGB(sp->format, 12, 200, 90);   /* opaque, non-uniform */
            Uint32 bgc = SDL_MapRGB(screen->format, 5, 5, 5);
            SDL_FillRect(sp, NULL, col);
            SDL_FillRect(screen, NULL, bgc);
            SDL_Rect dr = { 320, 200, 32, 32 };
            SDL_BlitSurface(sp, NULL, screen, &dr);
            SDL_UpdateWindowSurface(win);
            SELF_EQ_X32("VRAM no-ck blit centre == sprite", vram_pixel(336, 216), col);
            SELF_EQ_X32("VRAM no-ck blit outside == bg", vram_pixel(300, 200), bgc);
            SDL_FreeSurface(sp);
        }
    }

    /* FillRect now fills each row with SDL_memset4 — word-sized
     * store via Duff's device, equivalent to a per-word loop without
     * the inner branch.  Verify end-to-end through VRAM readback with
     * two distinct pixel values (white and black). */
    {
        const Uint32 white = 0xFFFFFFFFu;  /* uniform bytes → memset path */
        const Uint32 black = 0x00000000u;  /* uniform bytes → memset path */
        SDL_FillRect(screen, NULL, white);
        SDL_UpdateWindowSurface(win);
        SELF_EQ_X32("VRAM fill fill centre == white",
                    vram_pixel(W / 2, H / 2), white);
        SELF_EQ_X32("VRAM fill fill corner == white", vram_pixel(3, 3), white);

        SDL_FillRect(screen, NULL, white);
        SDL_Rect r2 = { 30, 40, 60, 20 };
        SDL_FillRect(screen, &r2, black);
        SDL_UpdateWindowSurface(win);
        SELF_EQ_X32("VRAM fill rect inside == black",
                    vram_pixel(45, 48), black);
        SELF_EQ_X32("VRAM fill rect outside == white",
                    vram_pixel(25, 45), white);
    }
}

/* ---- window / video layer ---- */
static void test_window_api(SDL_Window *win, SDL_Surface *screen) {
    (void)screen;
    Uint32 flags = SDL_GetWindowFlags(win);
    SELF_CHECK("GetWindowFlags has SHOWN", (flags & SDL_WINDOW_SHOWN) != 0);

    int w = 0, h = 0;
    SDL_GetWindowSize(win, &w, &h);
    SELF_CHECK("GetWindowSize returns requested", w == W && h == H);

    int x = -1, y = -1;
    SDL_GetWindowPosition(win, &x, &y);
    SELF_CHECK("GetWindowPosition returns 0", x == 0 && y == 0);

    SELF_EQ_X32("GetWindowPixelFormat RGBA32",
                (unsigned)SDL_GetWindowPixelFormat(win),
                (unsigned)SDL_PIXELFORMAT_RGBA32);

    SDL_DisplayMode dm;
    SELF_CHECK("GetDisplayMode(0,0) ok",
               SDL_GetDisplayMode(0, 0, &dm) == 0 && dm.w > 0 && dm.h > 0);
    SDL_DisplayMode cur;
    SELF_CHECK("GetCurrentDisplayMode ok", SDL_GetCurrentDisplayMode(0, &cur) == 0);
    SELF_EQ_X32("GetNumDisplayModes >=1",
                (unsigned)(SDL_GetNumDisplayModes(0) > 0), 1u);
}

/* ---- surface common conversions / clip ----- */
static void test_surface_api(SDL_Surface *screen) {
    SDL_Surface *s = SDL_CreateRGBSurface(0, 48, 32, 32, 0,0,0,0);
    if (!s) { ++g_fail; return; }
    SDL_FillRect(s, NULL, SDL_MapRGB(s->format, 200, 40, 40));

    SDL_Surface *dup = SDL_DuplicateSurface(s);
    SELF_CHECK("DuplicateSurface ok & pixel copied",
               dup != NULL && dup->pixels != NULL &&
               ((Uint32 *)dup->pixels)[0] == *((Uint32 *)s->pixels));

    SDL_Surface *cv = SDL_ConvertSurfaceFormat(s, SDL_PIXELFORMAT_RGBA32, 0);
    SELF_CHECK("ConvertSurfaceFormat ok", cv != NULL && cv->format->format == SDL_PIXELFORMAT_RGBA32);
    SELF_EQ_X32("Convert depth 32", (unsigned)(cv ? cv->format->BitsPerPixel : 0), 32u);
    if (dup) SDL_FreeSurface(dup);
    if (cv) SDL_FreeSurface(cv);
    SDL_FreeSurface(s);
}

/* ---- renderer pipeline ---- */
static void test_renderer_api(SDL_Window *win, SDL_Surface *screen) {
    (void)screen;
    SDL_Renderer *ren = SDL_CreateRenderer(win, -1, 0);
    SELF_CHECK("CreateRenderer ok", ren != NULL);
    if (!ren) { ++g_fail; return; }

    Uint8 r, g, b, a;
    SDL_SetRenderDrawColor(ren, 220, 30, 30, 255);
    SELF_CHECK("GetRenderDrawColor round-trip",
               SDL_GetRenderDrawColor(ren, &r, &g, &b, &a) == 0 &&
               r == 220 && g == 30 && b == 30 && a == 255);

    SDL_RenderClear(ren);
    /* renderer target is the window surface */
    SDL_RenderPresent(ren);
    Uint32 bg_c = SDL_MapRGB(screen->format, 8, 10, 26);
    Uint32 got_c = vram_pixel(W / 2, H / 2);
    SELF_CHECK("VRAM renderer clear changed centre (painted)",
               got_c != bg_c);

    /* Fill a rect with a different draw colour. */
    SDL_SetRenderDrawColor(ren, 40, 40, 220, 255);
    SDL_Rect rr = { 200, 200, 100, 80 };
    SDL_RenderFillRect(ren, &rr);
    SDL_RenderPresent(ren);
    Uint32 inr = vram_pixel(250, 240);
    SELF_CHECK("VRAM renderer fillrect changed centre (drawn)",
               inr != got_c);
    SELF_CHECK("VRAM renderer outside fillrect unchanged",
               vram_pixel(20, 20) == got_c);

    /* Texture + RenderCopyEx (rotation). */
    SDL_Surface *ts = SDL_CreateRGBSurface(0, 32, 32, 32, 0,0,0,0);
    if (ts) {
        SDL_FillRect(ts, NULL, SDL_MapRGB(ts->format, 220, 220, 40));
        SDL_Texture *tex = SDL_CreateTextureFromSurface(ren, ts);
        SELF_CHECK("CreateTextureFromSurface ok", tex != NULL);
        if (tex) {
            Uint32 fmtq; int aw, ah, acc;
            SDL_QueryTexture(tex, &fmtq, &acc, &aw, &ah);
            SELF_CHECK("QueryTexture matches 32x32 RGBA32",
                       aw == 32 && ah == 32 && fmtq == SDL_PIXELFORMAT_RGBA32);
            SELF_CHECK("TextureColorMod ok", SDL_SetTextureColorMod(tex, 120, 200, 80) == 0);
            SELF_CHECK("SetTextureBlendMode ok",
                       SDL_SetTextureBlendMode(tex, SDL_BLENDMODE_BLEND) == 0);
            SDL_Rect dst = { 300, 300, 80, 80 };
            SELF_EQ_X32("RenderCopyEx ok",
                        (unsigned)(SDL_RenderCopyEx(ren, tex, NULL, &dst, 25.0, NULL,
                                                    SDL_FLIP_HORIZONTAL) == 0), 1u);
            SDL_RenderPresent(ren);
            Uint32 got = vram_pixel(340, 340);            Uint8 gr = (Uint8)(got & 0xFF);
            SELF_CHECK("VRAM renderer texture drawn", gr >= 40);
            SDL_DestroyTexture(tex);
        }
        SDL_FreeSurface(ts);
    }

    SDL_DestroyRenderer(ren);
}

/* ---- RWops ---- */
static void test_rwops_api(void) {
    /* SDL_RWFromMem round-trip via write/seek/read/tell. */
    Uint8 mem[64];
    memset(mem, 0, sizeof(mem));
    SDL_RWops *rw = SDL_RWFromMem(mem, (int)sizeof(mem));
    SELF_CHECK("RWFromMem ok", rw != NULL);
    if (!rw) { ++g_fail; return; }

    Uint8 src[8] = {1,2,3,4,5,6,7,8};
    SELF_CHECK("RWWrite 8 bytes", SDL_RWwrite(rw, src, 1, 8) == 8);
    SELF_EQ_X32("RWTell after write", (unsigned long)SDL_RWtell(rw), 8ul);

    SELF_CHECK("RWSseek back", SDL_RWseek(rw, 0, RW_SEEK_SET) == 0);
    Uint8 buf[8];
    memset(buf, 0, sizeof(buf));
    SELF_CHECK("RWRead 8 bytes", SDL_RWread(rw, buf, 1, 8) == 8);
    SELF_CHECK("RWRead matches written", memcmp(buf, src, 8) == 0);

    /* SDL_AllocRW backs an anonymous memfs file; it may be unavailable on
     * a particular runtime, so we only sanity-check it does not crash. */
    SDL_RWops *a = SDL_AllocRW();
    if (a) SDL_FreeRW(a);

    SDL_FreeRW(rw);
}

