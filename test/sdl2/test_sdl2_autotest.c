/* ---- init / quit / subsystem lifecycle ---- */
static void test_init_quit_api(SDL_Window *win) {
    /* After SDL_Init(SDL_INIT_VIDEO) the VIDEO bit should be set. */
    SELF_CHECK("WasInit(0) reports subsystems",
               SDL_WasInit(0) != 0);
    SELF_CHECK("WasInit(VIDEO) has VIDEO bit",
               (SDL_WasInit(SDL_INIT_VIDEO) & SDL_INIT_VIDEO) != 0);

    /* Incremental subsystem init must not clobber existing state. */
    Uint32 before = SDL_GetTicks();
    SELF_EQ_X32("InitSubSystem(TIMER) == 0",
                (unsigned)SDL_InitSubSystem(SDL_INIT_TIMER), 0u);
    SELF_CHECK("WasInit(TIMER) has TIMER bit",
               (SDL_WasInit(SDL_INIT_TIMER) & SDL_INIT_TIMER) != 0);
    /* The existing window must still be valid (InitSubSystem did not reset). */
    SELF_CHECK("Window survives InitSubSystem",
               SDL_GetWindowSurface(win) != NULL &&
                   SDL_GetWindowSurface(win)->pixels != NULL);
    /* Tick base must not have been reset (ticks keep growing). */
    SELF_CHECK("Ticks not reset by InitSubSystem",
               SDL_GetTicks() >= before);

    /* Repeated SDL_Init must be idempotent: it must NOT reset global state and
       therefore must NOT clobber the already-created window. */
    Uint32 tick_before_reinit = SDL_GetTicks();
    SELF_EQ_X32("SDL_Init (repeat) == 0",
                (unsigned)SDL_Init(SDL_INIT_VIDEO), 0u);
    SELF_CHECK("Window survives repeated SDL_Init",
               SDL_GetWindowSurface(win) != NULL &&
                   SDL_GetWindowSurface(win)->pixels != NULL);
    SELF_CHECK("Tick base not reset by repeated SDL_Init",
               SDL_GetTicks() >= tick_before_reinit);

    /* Quit a subsystem clears its bit but leaves VIDEO alive. */
    SDL_QuitSubSystem(SDL_INIT_TIMER);
    SELF_CHECK("WasInit(TIMER) cleared after QuitSubSystem",
               (SDL_WasInit(SDL_INIT_TIMER) & SDL_INIT_TIMER) == 0);
    SELF_CHECK("WasInit(VIDEO) still set after TIMER quit",
               (SDL_WasInit(SDL_INIT_VIDEO) & SDL_INIT_VIDEO) != 0);

    /* Re-init TIMER for subsequent tests. */
    SDL_InitSubSystem(SDL_INIT_TIMER);
}

